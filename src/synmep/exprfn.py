"""Compile sympy expressions into model functions that mxlpy can parse back cheaply.

Two workarounds for mxlpy 0.68 (ADR 0003):

1. Functions generated by `mxlpy.meta.sympy_tools.expr_to_fn` call `math.exp` etc.,
   but the source parser resolves `math` through the function's parent module, which a
   generated function doesn't have, so the parse fails and the native integrator can't
   lower the model. Functions compiled here live in this module, which imports the
   modules the generated code uses.
2. The parser rebuilds `a + b + c + ...` left-associatively, re-flattening a growing
   `Add` at every step (quadratic in the number of terms). Long top-level sums are
   therefore emitted as balanced binary trees.
"""

from __future__ import annotations

import linecache
import math  # noqa: F401  (needed by the generated functions' module lookup)
import re
import uuid
from typing import TYPE_CHECKING, Any

import numpy  # noqa: F401
import scipy  # noqa: F401
import sympy

if TYPE_CHECKING:
    from collections.abc import Callable


def _code(expr: sympy.Expr) -> str:
    return sympy.pycode(expr, fully_qualified_modules=True, full_prec=True)


def _balanced(terms: list[str]) -> str:
    if len(terms) == 1:
        return terms[0]
    mid = len(terms) // 2
    return f"({_balanced(terms[:mid])} + {_balanced(terms[mid:])})"


def expr_fn(expr: sympy.Expr, origin: str) -> tuple[Callable[..., float], list[str]]:
    """Compile `expr` (free symbols = model names) into a function and its args."""
    args = sorted(str(s) for s in expr.free_symbols)
    name = "_" + re.sub(r"\W", "_", origin)
    if isinstance(expr, sympy.Add) and len(expr.args) > 8:
        body = _balanced([_code(t) for t in expr.args])
    else:
        body = _code(expr)
    src = f"def {name}({', '.join(args)}):\n    return {body}\n"
    filename = f"<synmep-generated-{uuid.uuid4().hex}>"
    linecache.cache[filename] = (
        len(src),
        None,
        src.splitlines(keepends=True),
        filename,
    )
    namespace: dict[str, Any] = {}
    exec(compile(src, filename, "exec"), globals(), namespace)  # noqa: S102
    fn = namespace[name]
    fn.__module__ = __name__
    return fn, args


def clip_zero(x: float) -> float:
    """max(x, 0) as a plain function, so sympy never sees Max(<huge expr>, 0)."""
    return max(x, 0.0)
