"""Compile sympy expressions into model functions that mxlpy can parse back.

Workaround for mxlpy 0.68: functions generated by `mxlpy.meta.sympy_tools.expr_to_fn`
call `math.exp` etc., but the source parser resolves `math` through the function's
parent module, which a generated function doesn't have. The parse then fails and
the native integrator can't lower the model. Re-homing the generated function in
this module (which imports the modules the generated code uses) fixes the lookup.
"""

from __future__ import annotations

import math  # noqa: F401  (needed by the generated functions' module lookup)
from typing import TYPE_CHECKING

import numpy  # noqa: F401
import scipy  # noqa: F401
from mxlpy.meta.sympy_tools import expr_to_fn

if TYPE_CHECKING:
    from collections.abc import Callable

    import sympy


def expr_fn(expr: sympy.Expr, origin: str) -> tuple[Callable[..., float], list[str]]:
    fn, args = expr_to_fn(expr, origin=origin)
    fn.__module__ = __name__
    return fn, args
